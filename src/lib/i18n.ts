export type TranslationKey = keyof typeof translations.ar

export function t(key: TranslationKey, lang: Language = 'ar'): string {
  return translations[lang][key] || translations.ar[key] || key
}

export function formatPrice(price: number, lang: Language = 'ar'): string {
  const locale = lang === 'ar' ? 'ar-DZ' : 'fr-DZ'
  const currency = lang === 'ar' ? 'دج' : 'DA'
  return new Intl.NumberFormat(locale).format(price) + ' ' + currency
}
